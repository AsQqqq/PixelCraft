/// Paints `icon` centred in `r`, each icon pixel a whole number of points (as large as fits in
/// 80 % of the rect).
pub fn paint(p: &Painter, r: Rect, icon: Icon, c: Color32) {
    let rows = bitmap(icon);
    let h = rows.len() as f32;
    let w = rows.iter().map(|r| r.len()).max().unwrap_or(0) as f32;
    if w == 0.0 || h == 0.0 {
        return;
    }
    let px = ((r.width().min(r.height()) * 0.8) / w.max(h)).floor().max(1.0);
    let origin = (r.center() - vec2(w * px, h * px) / 2.0).round();
    for (y, row) in rows.iter().enumerate() {
        for (x, ch) in row.chars().enumerate() {
            if ch == '#' {
                let min = pos2(origin.x + x as f32 * px, origin.y + y as f32 * px);
                p.rect_filled(Rect::from_min_size(min, vec2(px, px)), 0.0, c);
            }
        }
    }
}

/// A square pixel-art icon button: raised bevel, sunk while pressed, accent when selected.
pub fn button(ui: &mut egui::Ui, side: f32, icon: Icon, selected: bool, t: &Tokens) -> egui::Response {
    let (r, resp) = ui.allocate_exact_size(vec2(side, side), egui::Sense::click());
    let p = ui.painter();
    if selected {
        theme::bevel_selected(p, r, t);
    } else {
        let face = if resp.hovered() { t.button_hover } else { t.button };
        theme::bevel(p, r, face, resp.is_pointer_button_down_on(), t);
    }
    paint(p, r, icon, if selected { t.on_accent } else { t.text });
    resp
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_icon_is_rectangular() {
        let mut icons: Vec<Icon> = Tool::ALL.iter().map(|&t| Icon::Tool(t)).collect();
        icons.extend([
            Icon::First,
            Icon::Previous,
            Icon::Play,
            Icon::Pause,
            Icon::Next,
            Icon::Last,
            Icon::Eye,
            Icon::EyeClosed,
            Icon::Lock,
            Icon::Home,
            Icon::Close,
            Icon::Unsaved,
            Icon::Preview,
            Icon::Timeline,
            Icon::Stop,
            Icon::Fit,
        ]);
        for icon in icons {
            let rows = bitmap(icon);
            let w = rows.first().map_or(0, |r| r.len());
            assert!(w > 0 && rows.iter().all(|r| r.len() == w && r.chars().all(|c| c == '#' || c == '.')), "{icon:?}");
        }
    }
}
